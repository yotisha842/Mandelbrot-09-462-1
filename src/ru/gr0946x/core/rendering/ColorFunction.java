package ru.gr0946x.core.rendering;

import java.awt.*;

/**
 * Функциональный интерфейс для расчёта цвета точки фрактала.
 * Принимает нормализованное значение итераций [0.0, 1.0] и возвращает соответствующий Color.
 * Реализуется через лямбда-выражения для гибкой смены цветовых схем.
 */
@FunctionalInterface
public interface ColorFunction {
    //Вычисляет цвет для точки на основе доли пройденных итераций.
    Color getColor(float value);
}
