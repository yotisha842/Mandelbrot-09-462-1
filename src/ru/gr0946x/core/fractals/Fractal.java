/**
 * Определяет контракт для расчёта фракталов.
 * Возвращает нормализованную долю итераций [0.0, 1.0] для точки с координатами x, y.
 */
public interface Fractal {
    // Вычисляет, сколько шагов прошла точка до выхода за границу или достижения лимита.
    float inSetProbability(double x, double y);
}
